# Rules for variables
# 1. A variable name cannot start with a number.
# 2. A variable name cannot contain special characters like !, @, #, $, or -.
# 3. A variable can store different data types.

name = "John"

# String
user_name = "Alice"

# Integer
age = 30
computer_count = 20

# Float
balance = 100.50
print(type(balance))
# String
title = "Python is easy to learn"

# Boolean
is_active = True

# Example output ctrl+?
print("Name:", name)
print("Age:", age)
print("Balance:", balance)
print("Title:", title)
print("Active:", is_active)

# Invalid examples
# 1name = "John"
# $this = "hello world"
# my-name = "Python"

name = 'John'
last_name = "John"